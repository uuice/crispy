/**
 * Scope theme styles.css under html.{rootClass} for full isolation between skins.
 * Usage: node scripts/scope-theme-css.mjs [blog|cms|kb|all]
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import postcss from 'postcss'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const rootDir = path.resolve(__dirname, '..')

const THEMES = {
  blog: 'blog-skin',
  cms: 'cms-skin',
  kb: 'kb-skin',
}

function transformSelector(selector, rootClass) {
  let sel = selector.trim()
  const root = `html.${rootClass}`

  if (!sel) return sel

  // Already scoped
  if (sel.startsWith(`${root} `) || sel === root || sel.startsWith(`${root}.`) || sel.startsWith(`${root}[`)) {
    return sel
  }

  if (sel === ':root') return root

  if (sel === 'html') return root
  if (sel.startsWith('html[') || sel.startsWith('html:')) {
    return sel.replace(/^html/, root)
  }

  if (sel === '.dark') return `${root}.dark`
  if (sel.startsWith('.dark ')) {
    const rest = sel.slice(5).replace(/^body\.(?:blog|cms|kb)-skin/, 'body')
    return `${root}.dark ${rest}`
  }
  if (sel.startsWith('.dark.')) return `${root}.dark${sel.slice(5)}`

  if (sel === 'body') return `${root} body`

  if (sel.startsWith('body.')) {
    const skinPattern = /^body\.(?:blog|cms|kb)-skin/
    if (skinPattern.test(sel)) {
      return sel.replace(skinPattern, `${root} body`)
    }
    return `${root} ${sel}`
  }

  if (sel.startsWith('*,') || sel === '*') {
    return `${root} ${sel}`
  }

  return `${root} ${sel}`
}

function scopePlugin(rootClass) {
  return {
    postcssPlugin: 'scope-theme-css',
    Rule(rule) {
      if (rule.parent?.type === 'atrule' && rule.parent.name === 'keyframes') {
        return
      }

      rule.selectors = rule.selectors.map((selector) => transformSelector(selector, rootClass))
    },
  }
}
scopePlugin.postcss = true

function stripGlobalTailwindVariant(css) {
  // Rely on globals.css dark variant; theme file should not register global @custom-variant
  return css.replace(/^@custom-variant\s+dark\s+[^;]+;\s*/m, '')
}

async function scopeThemeFile(themeId, rootClass) {
  const filePath = path.join(rootDir, 'src/themes', themeId, 'styles.css')
  const source = fs.readFileSync(filePath, 'utf8')
  const cleaned = stripGlobalTailwindVariant(
    source.replace(/^\/\* Scoped to html\.\S+ — generated by scripts\/scope-theme-css\.mjs \*\/\s*/gm, ''),
  )

  const result = await postcss([scopePlugin(rootClass)]).process(cleaned, {
    from: filePath,
    to: filePath,
  })

  const css = result.css.replace(/\bbody\.(?:blog|cms|kb)-skin\b/g, 'body')

  const banner = `/* Scoped to html.${rootClass} — generated by scripts/scope-theme-css.mjs */\n`
  fs.writeFileSync(filePath, banner + css, 'utf8')
  console.log(`Scoped ${filePath} → html.${rootClass}`)
}

async function main() {
  const arg = process.argv[2] ?? 'all'
  const targets =
    arg === 'all' ? Object.entries(THEMES) : [[arg, THEMES[arg]]].filter(([, cls]) => Boolean(cls))

  if (!targets.length) {
    console.error(`Unknown theme "${arg}". Use blog, cms, kb, or all.`)
    process.exit(1)
  }

  for (const [themeId, rootClass] of targets) {
    await scopeThemeFile(themeId, rootClass)
  }
}

main().catch((error) => {
  console.error(error)
  process.exit(1)
})
